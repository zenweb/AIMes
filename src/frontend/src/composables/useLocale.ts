export function useLocale() {
  const t = (section: keyof (typeof messages)['zh-CN'], key: string) =>
    (messages[locale.value][section] as Record<string, string>)[key] ?? key

  const htmlLang = computed(() => locale.value)

  function setLocale(value: AppLocale) {
    locale.value = value
    if (typeof document !== 'undefined') document.documentElement.lang = value
    if (storage && typeof storage.setItem === 'function') storage.setItem(storageKey, value)
  }

  function toggleLocale() {
    setLocale(locale.value === 'zh-CN' ? 'en-US' : 'zh-CN')
  }

  return { locale, htmlLang, setLocale, toggleLocale, t }
}
