param(
    [string]$DatasetId = "DEMO-OTD-30-202605",
    [int]$Seed = 20260523,
    [string]$JsonOut = "src\frontend\public\reports\latest-ab-report.json",
    [string]$MarkdownOut = "_docs\_reports\20260524-demo-otd-30-ab-report.md"
)

$ErrorActionPreference = "Stop"

Write-Host ("AIMes A/B comparison real-run")
Write-Host ("Dataset: " + $DatasetId)
Write-Host ("Seed: " + $Seed)

$seedFile = "db\seed-demo-otd-30-202605.sql"
$dictionaryFile = "_docs\_design\20260524-demo-otd-30-data-dictionary.md"

if (-not (Test-Path -LiteralPath $seedFile)) {
    throw ("Missing SQL seed file: " + $seedFile)
}

if (-not (Test-Path -LiteralPath $dictionaryFile)) {
    throw ("Missing data dictionary: " + $dictionaryFile)
}

$matches = Select-String -Path $seedFile -Pattern "^\s*\('demo-otd-30-wo-\d{4}'"
$workOrderCount = ($matches | Measure-Object).Count
if ($workOrderCount -ne 30) {
    throw ("Expected exactly 30 DEMO-OTD work order rows in SQL seed, found " + $workOrderCount)
}

Write-Host "[1/2] Running RuleEngineBenchmarkTests..."
dotnet test src\tests\MES.Tests.Unit\MES.Tests.Unit.csproj --filter "FullyQualifiedName~RuleEngineBenchmarkTests"
if ($LASTEXITCODE -ne 0) {
    throw ("RuleEngineBenchmarkTests failed (exit code " + $LASTEXITCODE + ")")
}

Write-Host "[2/2] Running real .NET A/B benchmark via MES.Tools.AbBenchmark..."
dotnet run --project src\tools\MES.Tools.AbBenchmark\MES.Tools.AbBenchmark.csproj -p:UseSharedCompilation=false -- --dataset $DatasetId --seed $Seed --json-out $JsonOut --md-out $MarkdownOut
if ($LASTEXITCODE -ne 0) {
    throw ("MES.Tools.AbBenchmark failed (exit code " + $LASTEXITCODE + ")")
}

if (-not (Test-Path -LiteralPath $JsonOut)) {
    throw ("Expected JSON report at " + $JsonOut + " not generated by benchmark.")
}

if (-not (Test-Path -LiteralPath $MarkdownOut)) {
    throw ("Expected Markdown report at " + $MarkdownOut + " not generated by benchmark.")
}

Write-Host "A/B comparison real run complete."
Write-Host ("JSON report: " + $JsonOut)
Write-Host ("Markdown report: " + $MarkdownOut)
